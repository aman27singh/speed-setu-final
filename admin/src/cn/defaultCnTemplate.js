export function cloneTemplateConfig(config) {
  return JSON.parse(JSON.stringify(config || DEFAULT_CN_TEMPLATE_CONFIG));
}

export function mergeWithDefaultTemplate(partialConfig) {
  const base = cloneTemplateConfig(DEFAULT_CN_TEMPLATE_CONFIG);
  if (!partialConfig || typeof partialConfig !== 'object') {
    return base;
  }

  const mergedPage = { ...base.page, ...(partialConfig.page || {}) };
  const mergedCompanyInfo = { ...base.companyInfo, ...(partialConfig.companyInfo || {}) };

  const incomingById = new Map();
  if (Array.isArray(partialConfig.elements)) {
    partialConfig.elements.forEach((el) => {
      if (el && el.id) incomingById.set(el.id, el);
    });
  }

  const mergedElements = base.elements.map((defEl) => {
    const custom = incomingById.get(defEl.id);
    return custom ? { ...defEl, ...custom } : defEl;
  });

  const mergedCustomElements = Array.isArray(partialConfig.customElements)
    ? partialConfig.customElements.map((c) => ({ ...c }))
    : [];

  return {
    ...base,
    ...partialConfig,
    page: mergedPage,
    companyInfo: mergedCompanyInfo,
    elements: mergedElements,
    customElements: mergedCustomElements,
  };
}

